  @Override
  public void generateBlockStateModels(BlockStateModelGenerator blockModelGenerator) {
    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.ENDER_BLOCK);
    generateMaterialModels(blockModelGenerator, LighterEndBlocks.VIOLECITE);
    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.MISSING_TILE);
    for (Material jadestone : Arrays.asList(
        LighterEndBlocks.AZURE_JADESTONE,
        LighterEndBlocks.SANDY_JADESTONE,
        LighterEndBlocks.VIRID_JADESTONE
    )) {
      generateMaterialModels(blockModelGenerator, jadestone);
    }

//    blockModelGenerator.registerAxisRotated(
//        LighterEndBlocks.DRAGON_BONE_BLOCK, TexturedModel.CUBE_COLUMN
//    );

    /* Note: the below creates an (incorrect) model for the base dragon block. But because
             the (correct) model generated by the above commented-out code section is included
             in the non-generated assets folder, this one gets ignored. */
    BlockTexturePool texturePool = blockModelGenerator.registerCubeAllModelTexturePool(
        LighterEndBlocks.DRAGON_BONE_BLOCK
    );
    texturePool.stairs(LighterEndBlocks.DRAGON_BONE_STAIRS);
    texturePool.slab(LighterEndBlocks.DRAGON_BONE_SLAB);

    generateMaterialModels(blockModelGenerator, LighterEndBlocks.UMBRALITH);

    generateWoodModels(blockModelGenerator, LighterEndBlocks.TENANEA);
    blockModelGenerator.registerFlowerPotPlant(
        LighterEndBlocks.TENANEA_SAPLING,
        LighterEndBlocks.POTTED_TENANEA_SAPLING,
        CrossType.NOT_TINTED
    );
    blockModelGenerator.registerSingleton(LighterEndBlocks.TENANEA_LEAVES, TexturedModel.LEAVES);

    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.UMBRELLA_TREE_CLUSTER);
    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.UMBRELLA_TREE_CLUSTER_EMPTY);
    blockModelGenerator.registerFlowerPotPlant(
        LighterEndBlocks.UMBRELLA_TREE_SAPLING,
        LighterEndBlocks.POTTED_UMBRELLA_SAPLING,
        CrossType.NOT_TINTED
    );
    generateWoodModels(blockModelGenerator, LighterEndBlocks.UMBRELLA);

    generateWoodModels(blockModelGenerator, LighterEndBlocks.LOTUS);

    blockModelGenerator.registerFlowerPotPlant(
        LighterEndBlocks.GLOWSHROOM_SAPLING,
        LighterEndBlocks.POTTED_GLOWSHROOM_SAPLING,
        CrossType.EMISSIVE_NOT_TINTED
    );
    generateWoodModels(blockModelGenerator, LighterEndBlocks.GLOWSHROOM);

    blockModelGenerator.registerTintableCrossBlockState(
        LighterEndBlocks.AGAVE_SEED,
        CrossType.NOT_TINTED
    );

    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.EMERALD_ICE);
    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.FERROUS_ICE);
    blockModelGenerator.registerSimpleCubeAll(LighterEndBlocks.AUROUS_ICE);

    LighterEndBlocks.COPPER_CHANDELIERS.getWaxingMap()
        .forEach(
            (unwaxed, waxed) -> blockModelGenerator.registerWaxable(
                unwaxed.asItem(),
                waxed.asItem()
            )
        );

    generateMaterialModels(blockModelGenerator, LighterEndBlocks.BORNITE);

    generateWoodModels(blockModelGenerator, LighterEndBlocks.DRAGON);
    blockModelGenerator.registerFlowerPotPlant(
        LighterEndBlocks.DRAGON_SAPLING,
        LighterEndBlocks.POTTED_DRAGON_SAPLING,
        CrossType.NOT_TINTED
    );
    blockModelGenerator.registerSingleton(LighterEndBlocks.DRAGON_LEAVES, TexturedModel.LEAVES);
  }

  public static void generateMaterialModels(BlockStateModelGenerator blockModelGenerator,
      Material material) {
    blockModelGenerator.registerCubeAllModelTexturePool(
            material.baseBlock).stairs(material.baseStairs).slab(material.baseSlab)
        .wall(material.baseWall);

    blockModelGenerator.registerCubeAllModelTexturePool(material.bricks)
        .stairs(material.brickStairs).slab(material.brickSlab).wall(material.brickWall);

    blockModelGenerator.registerCubeAllModelTexturePool(material.polished)
        .stairs(material.polishedStairs).slab(material.polishedSlab).wall(material.polishedWall)
        .button(material.button).pressurePlate(material.pressurePlate);

    blockModelGenerator.registerCubeAllModelTexturePool(material.tiles).stairs(material.tileStairs)
        .slab(material.tileSlab).wall(material.tileWall);

    blockModelGenerator.registerAxisRotated(material.pillar, TexturedModel.CUBE_COLUMN);
  }

  public static void generateWoodModels(
      BlockStateModelGenerator blockModelGenerator,
      WoodSet wood
  ) {
    blockModelGenerator.createLogTexturePool(wood.log).log(wood.log).wood(wood.wood);
    blockModelGenerator.createLogTexturePool(wood.strippedLog).log(wood.strippedLog)
        .wood(wood.strippedWood);
    blockModelGenerator.registerCubeAllModelTexturePool(wood.planks).stairs(wood.stairs)
        .slab(wood.slab).fence(wood.fence).fenceGate(wood.gate).button(wood.button)
        .pressurePlate(wood.pressurePlate);
    blockModelGenerator.registerDoor(wood.door);
    blockModelGenerator.registerTrapdoor(wood.trapdoor);
    blockModelGenerator.registerHangingSign(wood.strippedLog, wood.sign, wood.wallSign);
    blockModelGenerator.registerHangingSign(wood.strippedLog, wood.hangingSign,
        wood.wallHangingSign);
    blockModelGenerator.registerShelf(wood.shelf, wood.strippedLog);
  }

